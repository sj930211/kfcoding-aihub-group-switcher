import fs from 'node:fs';
import vm from 'node:vm';
import assert from 'node:assert/strict';
const ctx={__KFCODING_GROUP_SWITCHER_TEST__:true};
vm.runInNewContext(fs.readFileSync(new URL('../kfcoding-group-switcher.user.js',import.meta.url),'utf8'),ctx);
const api=ctx.__KFCODING_GROUP_SWITCHER_API__;
const now=Date.parse('2026-11-02T01:00:00Z'), fresh=new Date(now).toISOString(), later=new Date(now+60_000).toISOString();
const normalizedKey=api.normalizeAihubToken({id:1,group_id:296,group:{id:296,name:'Kimi'}});
assert.equal(api.normalizeAihubToken(normalizedKey).group,'Kimi','normalized keys retain group IDs and display names');
const detail=(model,overrides={})=>({applicable:true,model,status:'passed',execution_complete:true,detected_at:fresh,presentation:{text:{result:true}},...overrides});
const metrics=(overrides={})=>({success_rate:.99,tps:60,sample_count:100,range_cache:{cache_hit_rate:.7,usage_records:80,ready:true,stale:false,refreshed_at:fresh},...overrides});
const item=(id,model,overrides={})=>({group_id:id,code:'g'+id,platform:id===1?'kimi':'openai',rate_multiplier:1,group_models:[model],model_detection:detail(model),summary_models:{[model]:metrics()},...overrides});
const items=[item(1,'kimi-k3'),item(2,'gpt-6.1-sol')];
const groups=items.map(x=>({id:x.group_id,name:x.code}));
const config=api.sanitizeConfig({models:['gpt-6.1-sol','kimi-k3']});
const evaluate=(entries=items,settings=config,overrides={})=>{
  const data=api.normalizeAihubProviderData({version:2,summary_range:'1h',generated_at:fresh,items:entries,...overrides},{});
  return api.evaluateAihubCandidates(data.summary,{},groups,{},settings,now);
};
const rows=evaluate();
assert.equal(rows.length,2);
assert.equal(rows[0].available,true,'only the exact latest detected model is needed, not all selected models');
assert.equal(rows[1].available,true);
assert.equal(rows[0].aihubMetricModel,'kimi-k3');
assert.equal(rows[1].aihubMetricModel,'gpt-6.1-sol');
assert.equal(rows[0].aggregateSuccess,99);
assert.equal(rows[0].cacheHitRate,70);
assert.equal(rows[0].outputTokensPerSecond,60);
const catalog=api.buildAihubModelCatalog({apis:items}).data;
assert.deepEqual(Array.from(catalog,x=>x.model_name).sort(),['gpt-6.1-sol','kimi-k3']);
assert.deepEqual(Array.from(catalog.find(x=>x.model_name==='kimi-k3').platforms),['kimi']);
const sol=api.sanitizeConfig({models:['gpt-6.1-sol']});
assert.equal(evaluate([items[0]],sol)[0].available,false,'another model cannot borrow the selected model metrics');
assert.ok(evaluate([items[0]],sol)[0].reasons.includes('model-detection-model-mismatch'));
for(const group_models of [[],null,['unrelated']]){
  const row=evaluate([{...items[1],group_models,model_cards:[{model:'gpt-6.1-sol',health:'healthy'}]}],sol)[0];
  assert.equal(row.available,false,'actual group model support is authoritative');
  assert.ok(row.reasons.includes('model-unsupported'));
}
const one=(overrides={},settings=sol)=>evaluate([{...items[1],...overrides}],settings)[0];
assert.equal(one({model_detection:null}).available,false,'legacy summaries alone do not prove model detection');
assert.equal(one({model_detection:detail('gpt-6.1-sol',{presentation:{text:{result:false}}})}).available,false);
assert.equal(one({model_detection:detail('gpt-6.1-sol',{execution_complete:false})}).available,false);
assert.equal(one({model_detection:detail('gpt-6.1-sol',{status:'refreshing'})}).available,false);
assert.equal(one({model_detection:detail('gpt-6.1-sol',{model:'gpt-6.1-sol-plus'})}).available,false,'matching is exact rather than prefix based');
assert.equal(one({model_detection:detail('gpt-6.1-sol',{detected_at:'2026-11-01T20:00:00Z',expires_at:later})}).available,true,'valid server expiry overrides old detected_at');
assert.equal(one({model_detection:detail('gpt-6.1-sol',{expires_at:'bad'})}).available,false);
assert.equal(one({model_detection:detail('gpt-6.1-sol',{expires_at:new Date(now-1).toISOString()})}).available,false);
assert.equal(one({model_detection:detail('gpt-6.1-sol',{stages:[{status:'failed',execution_complete:true,result:false}]})}).available,false,'failed stage overrides top-level pass');
assert.equal(api.sanitizeConfig({requireModelDetection:false}).requireModelDetection,true,'strict detection cannot be disabled');
assert.equal(one({probe_model:'kimi-k3',available:false,model_cards:[{model:'gpt-6.1-sol',health:'failed'}],firstTokenLatencyMs:999999}).available,true,'old probes, cards and latency limits do not override exact 1h details');
const failedDetail=detail('gpt-6.1-sol',{status:'failed',presentation:{text:{result:false}},expires_at:later});
assert.equal(api.candidateHasExplicitHealthFailure(one({model_detection:failedDetail}),sol),true,'fresh explicit failed detection is a failure');
assert.equal(api.candidateHasExplicitHealthFailure(one({model_detection:{...failedDetail,expires_at:'bad'}}),sol),false,'invalid evidence does not become a measured failure');
assert.equal(api.candidateHasExplicitHealthFailure(one({model_detection:{...failedDetail,model:'kimi-k3'}}),sol),false,'unselected model failure cannot fail the business model');
const low=one({summary_models:{'gpt-6.1-sol':metrics({success_rate:.2})}});
assert.equal(api.candidateHasExplicitHealthFailure(low,sol),true,'fresh 1h low success is explicit failure');
const missing=one({summary_models:{'gpt-6.1-sol':metrics({success_rate:null})}});
assert.ok(Number.isNaN(missing.aggregateSuccess));
assert.equal(api.candidateHasExplicitHealthFailure(missing,sol),false,'missing rate remains unknown');
const zero=one({summary_models:{'gpt-6.1-sol':metrics({success_rate:0})}});
assert.equal(api.candidateHasExplicitHealthFailure(zero,sol),true,'measured zero is preserved');
const stale=api.normalizeAihubProviderData({version:2,summary_range:'1h',generated_at:'2020-01-01',items:[{...items[1],summary_models:{'gpt-6.1-sol':metrics({success_rate:.2})}}]},{});
assert.equal(api.candidateHasExplicitHealthFailure(api.evaluateAihubCandidates(stale.summary,{},groups,{},sol,now)[0],sol),false,'old metrics cannot borrow current detail freshness');
console.log('PASS AIHub exact group-model details, per-group metrics, mandatory detection, freshness and explicit failure evidence (local fixtures)');
