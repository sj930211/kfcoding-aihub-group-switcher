import assert from 'node:assert/strict';
import { qualityRuntime } from './fixtures/image-quality-runtime.mjs';
const { ctx, rows, images, calls, catalog, writes, reads } = qualityRuntime();
assert.equal(images.length, 0); assert.equal(calls.length, 0, 'directory refresh must not fetch images or score');
await ctx.runImageQuality({ candidate: rows[0] });
assert.equal(ctx.candidateImageQuality(rows[0]).score, 85);
const first = ctx.candidateImageQuality(rows[0]);
catalog();
assert.equal(ctx.candidateImageQuality(rows[0]), first, 'unchanged page records remain visible on ordinary polling');
assert.equal(images.length, 1); assert.equal(calls.length, 1);
const latest = { ...rows[0], detectionMedia: { ...rows[0].detectionMedia, publishedAt: 'v2' } };
catalog([latest, ...rows.slice(1)]);
assert.equal(ctx.candidateImageQuality(latest), null, 'changed picture must remove page-only evaluation');
assert.equal(images.length, 1); assert.equal(calls.length, 1);
await ctx.runImageQuality({ candidate: latest });
assert.equal(ctx.candidateImageQuality(latest).score, 85);
catalog(rows.map(row => ({ ...row, detectionMedia: null })));
assert.equal(ctx.imageQuality.records.size, 0);
assert(reads.every(key => key === 'watermark')); assert(writes.every(key => key === 'watermark'), 'only directory coordination may persist');
let release;
catalog(rows);
ctx.respond = async () => { await new Promise(resolve => { release = resolve; }); return new Response('{}'); };
const pending = ctx.runImageQuality({ candidate: rows[0] });
while (!release) await new Promise(resolve => setTimeout(resolve, 1));
catalog([latest]); release();
await assert.rejects(pending, error => error.code === 'IMAGE_CATALOG_STALE');
assert.equal(ctx.imageQuality.records.size, 0, 'stale results must not be published');
console.log('PASS directory refresh performs zero downloads/inference; page-only records survive polling, retire changed sources and reject in-flight stale results');
